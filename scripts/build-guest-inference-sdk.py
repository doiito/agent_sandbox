#!/usr/bin/env python3
"""Generate shared, dependency-free guest validation contracts from host SDKs."""
import argparse
import ast
import hashlib
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parent.parent


def python_contract():
    text = (ROOT / 'sdk/python/osv_sandbox_client.py').read_text()
    names = ['_SESSION_ID', '_INFERENCE_ENDPOINT', '_INFERENCE_U64', 'SandboxError', 'ConfigurationError',
             'TransportError', 'ProtocolError', 'UnsupportedCapability', 'APIError', 'InferenceError',
             '_preview_timestamp', '_inference_id', '_inference_units', '_inference_price', '_inference_json',
             '_inference_integer', '_inference_receipt', '_inference_bill', '_inference_policy_document', 'InferenceResult']
    lines = text.splitlines(keepends=True)
    selected = {}
    for node in ast.parse(text).body:
        name = getattr(node, 'name', None)
        if isinstance(node, ast.Assign) and len(node.targets) == 1 and isinstance(node.targets[0], ast.Name):
            name = node.targets[0].id
        if name in names:
            assert name not in selected, name
            first = min([node.lineno, *(item.lineno for item in getattr(node, 'decorator_list', []))])
            selected[name] = ''.join(lines[first - 1:node.end_lineno]).rstrip()
    assert set(selected) == set(names), set(names) - set(selected)
    body = '\n\n\n'.join(selected[name] for name in names) + '\n'
    return ('# Generated by scripts/build-guest-inference-sdk.py; do not edit.\n'
            '# Selected canonical definitions SHA256: ' + hashlib.sha256(body.encode()).hexdigest() + '\n'
            'from __future__ import annotations\n'
            'from dataclasses import dataclass\nfrom datetime import datetime, timezone\n'
            'from typing import Any\nimport json\nimport math\nimport re\n\n' + body)


def node_contract():
    text = (ROOT / 'sdk/node/index.js').read_text()
    names = ['SESSION_ID', 'INFERENCE_ENDPOINT', 'INFERENCE_U64', 'SandboxError', 'ConfigurationError',
             'TransportError', 'ProtocolError', 'UnsupportedCapability', 'APIError', 'InferenceError',
             'requireObject', 'previewTimestamp', 'inferenceId', 'inferenceUnits', 'inferencePrice',
             'inferenceKeys', 'inferenceInteger', 'inferenceJSON', 'inferenceReceipt', 'inferenceBill',
             'inferencePolicyDocument']
    chunks = []
    for name in names:
        # Only named top-level declarations with unindented closing braces.
        # A missing/duplicate boundary fails generation, never silently copies
        # adjacent network or host client implementation.
        pattern = (r'^(?:export )?(?:(?:const ' + re.escape(name) + r' = [^\n]+;)|'
                   r'(?:(?:function|class) ' + re.escape(name) + r'\b[^\n]*\{[^\n]*\})|'
                   r'(?:(?:function|class) ' + re.escape(name) + r'\b[^\n]*\{\n[\s\S]*?^\}))$')
        matches = list(re.finditer(pattern, text, re.MULTILINE))
        assert len(matches) == 1, (name, len(matches))
        chunks.append(matches[0].group(0).removeprefix('export '))
    body = '\n\n'.join(chunks) + '\n'
    exports = [name for name in names if name not in {'SESSION_ID', 'INFERENCE_ENDPOINT', 'INFERENCE_U64'}]
    return ('// Generated by scripts/build-guest-inference-sdk.py; do not edit.\n'
            '// Selected canonical definitions SHA256: ' + hashlib.sha256(body.encode()).hexdigest() + '\n'
            "'use strict';\n" + body + '\nmodule.exports = {' + ', '.join(exports + ['INFERENCE_ENDPOINT']) + '};\n')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    outputs = {'guest-sdk/python/remote_infer/_contract.py': python_contract(),
               'guest-sdk/node/inference-contract.cjs': node_contract()}
    for relative, content in outputs.items():
        path = ROOT / relative
        if args.check:
            assert path.is_file() and path.read_text() == content, 'Generated contract drift: ' + relative
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
    print('Guest inference contracts ' + ('checked' if args.check else 'generated') + ': Python and Node')


if __name__ == '__main__':
    main()
