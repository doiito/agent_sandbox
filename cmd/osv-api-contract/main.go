package main

import (
	"bytes"
	"flag"
	"fmt"
	"os"
	"path/filepath"

	"github.com/doiito/agent_sandbox/internal/apicontract"
)

func main() {
	root := flag.String("source-root", ".", "project source root")
	output := flag.String("output", "api/contracts/openapi.json", "canonical output or file to check")
	check := flag.Bool("check", false, "reject stale/missing output instead of writing")
	flag.Parse()
	if flag.NArg() != 0 {
		fmt.Fprintln(os.Stderr, "unexpected positional arguments")
		os.Exit(2)
	}
	data, err := apicontract.Generate(*root)
	if err == nil {
		data = append(data, '\n')
		if *check {
			var current []byte
			current, err = os.ReadFile(*output)
			if err == nil && !bytes.Equal(current, data) {
				err = fmt.Errorf("stale HTTP contract: regenerate %s", *output)
			}
		} else {
			err = os.MkdirAll(filepath.Dir(*output), 0o755)
			if err == nil {
				err = os.WriteFile(*output, data, 0o644)
			}
		}
	}
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	fmt.Printf("HTTP contract: %d registered operations, generated bytes match=%v\n", len(apicontract.RoutePatterns()), *check)
}
